const BLOCK_START = '<!-- rensei-kata:start -->';
const BLOCK_END = '<!-- rensei-kata:end -->';

function updateClaudeMd(targetDir, importPath) {
  const file = path.join(targetDir, 'CLAUDE.md');
  const block = `${BLOCK_START}
<!-- Managed by rensei-kata. Edit .rensei/ and run \`npx rensei-kata build\`. -->
@${importPath}
${BLOCK_END}`;

  if (!exists(file)) {
    write(file, `# Project\n\n${block}\n`);
    return 'created';
  }
  const content = read(file);
  const re = new RegExp(`${BLOCK_START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${BLOCK_END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`);
  if (re.test(content)) {
    write(file, content.replace(re, block));
    return 'updated';
  }
  write(file, `${content.trimEnd()}\n\n${block}\n`);
  return 'appended';
}

// OpenCode agents read AGENTS.md (same managed-block mechanic as CLAUDE.md).
function updateAgentsMd(targetDir, importPath) {
  const file = path.join(targetDir, 'AGENTS.md');
  const block = `${BLOCK_START}
<!-- Managed by rensei-kata. Edit .rensei/ and run \`npx rensei-kata build --target opencode\`. -->
@${importPath}
${BLOCK_END}`;

  if (!exists(file)) {
    write(file, `# Agents\n\n${block}\n`);
    return 'created';
  }
  const content = read(file);
  const re = new RegExp(`${BLOCK_START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${BLOCK_END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`);
  if (re.test(content)) {
    write(file, content.replace(re, block));
    return 'updated';
  }
  write(file, `${content.trimEnd()}\n\n${block}\n`);
  return 'appended';
}

