function flowChain(graph) {
  // Main path from entry, following first-visit edges (ignores back edges).
  const labels = n => (graph.nodes[n] && (graph.nodes[n].label || n)) || n;
  const chain = [];
  const visited = new Set();
  let current = graph.entry;
  while (current && !visited.has(current)) {
    visited.add(current);
    chain.push(labels(current));
    const next = (graph.edges || []).find(e => e.from === current && !visited.has(e.to));
    current = next && next.to;
  }
  return chain;
}

function compileRenseiCommand(core) {
  const { graph, agents } = core;
  const roster = [...agents.keys()].map(a => `@${a}`).join(', ');
  return `${GENERATED_HEADER}
Load the rensei (錬成) methodology into this session.

## What to do
1. Read: .rensei/RENSEI.md (the compiled methodology — config, flow, quality gates)
2. Confirm agents available: ${roster}
3. Acknowledge: "rensei loaded. ${agents.size} agents ready. @gate evaluates every request first."

The loop: ${flowChain(graph).join(' → ')}

$ARGUMENTS
`;
}

function compileRenseiDoc(core) {
  const { graph, config, agents } = core;
  const L = [];
  L.push(GENERATED_HEADER);
  L.push(`# rensei — Iterative AI Development Framework

> **rensei (錬成):** Refinamiento mediante repetición. Forjar, templar, corregir, repetir — hasta que el resultado sea excelente.
>
> **Source of truth:** \`.rensei/rensei.graph.yaml\`. This file is GENERATED — edit the graph/config and run \`npx rensei-kata build\`.

---

## Configuration

\`\`\`yaml
MODELS:
${Object.entries(config.MODELS || {}).map(([k, v]) => `  ${k}: ${v}`).join('\n')}

EFFORT:
${Object.entries(config.EFFORT || {}).map(([k, v]) => `  ${k}: ${v}`).join('\n')}

ITERATIONS:
${Object.entries(config.ITERATIONS || {}).map(([k, v]) => `  ${k}: ${v}`).join('\n')}

SDD_TOOL: ${config.SDD_TOOL}
DESIGN_TOOL: ${config.DESIGN_TOOL}
\`\`\`

---

## The Flow

\`\`\`
${flowChain(graph).join(' → ')}
                    └────────── correction loop (max ${resolveVar('$ITERATIONS.correction_loop', config)}×): QUALITY → CORRECT → SELF-CRITIQUE ──────────┘
\`\`\`

---

## The Agents

| Agent | Alias | Loop phases | Model | Standalone |
|-------|-------|-------------|-------|------------|`);

  for (const [name, { def }] of agents) {
    const phases = Object.entries(graph.nodes)
      .filter(([, n]) => !n.terminal && n.agent === name)
      .map(([pn, n]) => n.label || pn)
      .join(', ') || 'on-demand';
    L.push(`| **@${name}** | \`${def.alias}\` | ${phases} | ${resolveModel(config, def.model)} | \`${def.standalone || '—'}\` |`);
  }

  L.push(`
---

## Phase Table (from the graph)

| Phase | Agent | Model | Effort | Enters when |
|-------|-------|-------|--------|-------------|`);
  for (const [nodeName, node] of Object.entries(graph.nodes)) {
    if (node.terminal) continue;
    const incoming = (graph.edges || []).filter(e => e.to === nodeName && e.when).map(e => e.when).join(' OR ') || '—';
    L.push(`| ${node.label || nodeName} | @${node.agent} | ${resolveModel(config, node.model)} | ${resolveEffort(config, node.effort)} | ${incoming} |`);
  }

  L.push(`
---

## Quality Gates (from the graph)

| Transition | Condition |`);
  for (const e of graph.edges || []) {
    if (!e.when) continue;
    const max = e.max !== undefined ? ` (max ${resolveVar(e.max, config)}×)` : '';
    L.push(`| ${e.from} → ${e.to} | ${e.when}${max} |`);
  }

  L.push(`
---

## Skills Registry (optional, configurable)

Skills are declared here and assigned per agent (\`agents/<name>/agent.yaml\`) or per phase (\`nodes.<phase>.skills\` in the graph — editable in \`npx rensei-kata studio\`). Agents load them only when the task calls for it.

| Skill | Purpose | Used by |
|-------|---------|---------|`);
  const registry = config.SKILLS || {};
  for (const [skill, purpose] of Object.entries(registry)) {
    const users = [];
    for (const [agentName, { def }] of agents) {
      const agentDefault = (def.skills || []).includes(skill);
      const nodeUse = Object.values(graph.nodes).some(n => n.agent === agentName && (n.skills || []).includes(skill));
      if (agentDefault || nodeUse) users.push(`@${agentName}`);
    }
    L.push(`| \`${skill}\` | ${purpose} | ${users.join(', ') || '—'} |`);
  }

  L.push(`
## Reference Docs

| Doc | What's in it |
|-----|--------------|`);
  for (const filename of core.reference.keys()) {
    const slug = filename.replace(/\.md$/, '');
    L.push(`| [reference/${filename}](reference/${filename}) | ${REFERENCE_BLURBS[slug] || '—'} |`);
  }

  L.push(`
## Prompt Templates

Tool-agnostic templates in \`.rensei/prompts/\` — usable with any runtime (Claude Code print mode, OpenCode, CI):

${[...core.prompts.keys()].map(f => `- \`prompts/${f}\``).join('\n')}
`);

  L.push(`
---

## Anti-Patterns

- ❌ Skip self-critique ("the reviewer will catch it")
- ❌ Implement without a plan
- ❌ Use deep_reasoning for routine CRUD
- ❌ Use routine for architectural decisions
- ❌ Skip gate evaluation (guess instead of decide)
- ❌ Generate designs without DESIGN.md as source of truth
- ❌ "Close enough" — if it's not right, it's wrong
`);
  return L.join('\n');
}

