const GENERATED_HEADER = '<!-- GENERATED by rensei-kata from rensei.graph.yaml — do not edit directly; edit .rensei/ and run `npx rensei-kata build` -->\n';

const MANIFEST_FILE = 'build-manifest.json';

// Protocol appended to every compiled agent that owns loop phases: the agents
// keep .rensei/state.json current so `rensei-kata status` can observe the loop.
const STATE_PROTOCOL = `
## Loop State (keep it current)

You are part of the rensei loop — record progress so it stays observable:

    npx rensei-kata status --set <phase>           # when you START a phase (id from the table above)
    npx rensei-kata status --note "what happened"  # on meaningful gate decisions or findings

One call per phase entry is enough. Never edit .rensei/state.json by hand.
`;

function sha256(text) {
  return crypto.createHash('sha256').update(text, 'utf8').digest('hex');
}

// Drift = a generated artifact was hand-edited after the last build. The next
// build would silently destroy that work — surface it instead.
function checkDrift(targetDir) {
  const manifestFile = path.join(targetDir, '.rensei', MANIFEST_FILE);
  if (!exists(manifestFile)) return [];
  let manifest;
  try {
    manifest = JSON.parse(read(manifestFile));
  } catch (e) {
    return [];
  }
  const drift = [];
  for (const [rel, hash] of Object.entries(manifest.files || {})) {
    const file = path.join(targetDir, rel);
    if (!exists(file)) { drift.push({ file: rel, kind: 'deleted' }); continue; }
    if (sha256(read(file)) !== hash) drift.push({ file: rel, kind: 'edited' });
  }
  return drift;
}

function driftWarnings(drift) {
  return drift.map(d =>
    d.kind === 'edited'
      ? `generated file was hand-edited since the last build: ${d.file} — move the change into .rensei/ (agents/<n>/prompt.md, fragments/, graph) or it will be overwritten on the next build`
      : `generated file was deleted since the last build: ${d.file} — run \`npx rensei-kata build\` to restore it`);
}

const REFERENCE_BLURBS = {
  'decision-framework': 'Full @gate decision logic — OpenSpec levels, visual criteria, edge cases',
  'model-routing': 'Which model for which task — profiles, effort guide, cost awareness',
};

function resolveModel(config, tier, runtime) {
  const t = runtimeTable(config, 'MODELS', runtime);
  return (t && t[tier]) || tier || 'sonnet';
}

function resolveEffort(config, tier, runtime) {
  const t = runtimeTable(config, 'EFFORT', runtime);
  return (t && t[tier]) || tier || 'medium';
}

// MODELS/EFFORT may be flat (one table for every runtime) or nested per
// runtime ({claude:{...}, codex:{...}}). Resolve to ONE runtime's table.
function runtimeTable(config, key, runtime) {
  const raw = config && config[key];
  if (!raw || typeof raw !== 'object') return raw;
  const values = Object.values(raw);
  const nested = values.length > 0 && values.every(v => v && typeof v === 'object');
  if (!nested) return raw;
  return raw[runtime] || raw.claude || values[0];
}

const RUNTIME_OF_TARGET = { claude: 'claude', opencode: 'opencode', codex: 'codex', all: null };

