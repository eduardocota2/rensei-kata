function compile(core, targetDir, { global: isGlobal = false, target = 'claude', runtime = null } = {}) {
  const written = [];
  const targets = target === 'all' ? ['claude', 'opencode'] : [target];
  const renseiDir = path.join(targetDir, '.rensei');
  const manifest = { version: 1, target, files: {} };
  const track = (abs) => {
    const rel = toPosix(path.relative(targetDir, abs));
    manifest.files[rel] = sha256(read(abs));
  };

  // The graph is the source of truth: only nodes in it are compiled. Agents
  // lingering in .rensei/agents/ after a node was deleted (or renamed away)
  // are GHOSTS — they must not reach the runtime. on_demand helpers are the
  // only exception (sentinel: outside the loop, invocable standalone).
  const fs = require('fs');
  const graphAgents = new Set();
  for (const [id, node] of Object.entries(core.graph.nodes || {})) {
    if (!node.terminal) graphAgents.add(id);
  }
  const onDemand = new Set();
  for (const [name, { def }] of core.agents) {
    if (def && def.on_demand) onDemand.add(name);
  }
  const liveAgents = new Map();
  for (const [name, agent] of core.agents) {
    if (graphAgents.has(name) || onDemand.has(name)) liveAgents.set(name, agent);
  }
  const ghosts = [];
  for (const [name, agent] of core.agents) {
    if (!liveAgents.has(name)) ghosts.push({ name, agent });
  }
  const purged = [];

  for (const t of targets) {
    // claude → .claude/{agents,commands,rules} · opencode → .opencode/{agents,commands,rule}
    // (opencode uses PLURAL for agents/commands, singular for rule — per its docs)
    const isOpen = t === 'opencode' || t === 'codex';
    const base = isOpen ? path.join(targetDir, '.opencode') : path.join(targetDir, '.claude');
    const agentsDir = isOpen ? path.join(base, 'agents') : path.join(base, 'agents');
    const commandsDir = isOpen ? path.join(base, 'commands') : path.join(base, 'commands');
    const rulesDir = isOpen ? path.join(base, 'rule') : path.join(base, 'rules');
    const rt = runtime || RUNTIME_OF_TARGET[t] || core.config.RUNTIME || 'claude';

    // 1. agents — graph-scoped; ghosts are REMOVED from the runtime dirs so
    //    deleted agents stop existing everywhere at once
    for (const [name, agent] of liveAgents) {
      const file = path.join(agentsDir, `${name}.md`);
      write(file, compileAgent(name, agent, core, { target: t, runtime: rt }));
      written.push(file);
    }
    for (const g of ghosts) {
      for (const ghost of [path.join(agentsDir, `${g.name}.md`), path.join(agentsDir, `${g.name}.yaml`)]) {
        if (exists(ghost)) { fs.rmSync(ghost); purged.push(toPosix(path.relative(targetDir, ghost))); }
      }
    }

    // 2. commands — with a description frontmatter (both runtimes show it in
    //    their slash-command pickers)
    const kataFile = path.join(commandsDir, 'kata.md');
    write(kataFile, `---\ndescription: Dispatch a request to the right rensei agent (ES/EN) — no agent roster knowledge needed\n---\n${compileKata(core)}`);
    written.push(kataFile);

    const renseiCmdFile = path.join(commandsDir, 'rensei.md');
    write(renseiCmdFile, `---\ndescription: Run the rensei loop on a task — graph-compiled execution protocol (phases, gates, bounds)\n---\n${compileRenseiCommand(core)}`);
    written.push(renseiCmdFile);

    // 3. rules
    for (const [filename, content] of core.rules) {
      const file = path.join(rulesDir, filename);
      write(file, content);
      written.push(file);
    }

    // 4. entry-point managed block: CLAUDE.md (claude) / AGENTS.md (opencode/codex)
    const importPath = isGlobal
      ? toPosix(path.join(targetDir, '.rensei', 'RENSEI.md'))
      : '.rensei/RENSEI.md';
    if (isOpen) updateAgentsMd(targetDir, importPath, t);
    else updateClaudeMd(targetDir, importPath);
  }

  // 5. compiled methodology doc + diagram live next to the graph (target-shared)
  const docFile = path.join(renseiDir, 'RENSEI.md');
  write(docFile, compileRenseiDoc(core, runtime));
  written.push(docFile);

  const diagramFile = path.join(renseiDir, 'graph.html');
  write(diagramFile, renderDiagram(core));
  written.push(diagramFile);

  // 6. framework-managed reference docs + prompt templates (overwrite is safe:
  //    these are not user data — user edits belong in graph/config/agents)
  for (const [filename, content] of core.reference) {
    const file = path.join(renseiDir, 'reference', filename);
    write(file, content);
    written.push(file);
  }
  for (const [filename, content] of core.prompts) {
    const file = path.join(renseiDir, 'prompts', filename);
    write(file, content);
    written.push(file);
  }

  // 7. build manifest — lets validate/doctor detect hand-edited artifacts
  for (const f of written) track(f);
  const manifestFile = path.join(renseiDir, MANIFEST_FILE);
  write(manifestFile, JSON.stringify(manifest, null, 2) + '\n');
  written.push(manifestFile);

  const mdActions = [];
  if (targets.includes('claude')) mdActions.push('CLAUDE.md updated (managed block)');
  if (targets.some(t => t === 'opencode' || t === 'codex')) mdActions.push('AGENTS.md updated (managed block)');
  const out = { written, claudeMdAction: mdActions.join(' · ') };
  if (purged.length) out.purged = purged;
  if (ghosts.length) out.ghostsInRensei = ghosts.map(g => g.name); // .rensei/agents/ dirs kept (user data)
  return out;
}

