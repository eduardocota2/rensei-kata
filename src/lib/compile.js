function triggerSection(name, def, suffix, triggers) {
  const lines = [];
  lines.push(`### → @${name}${suffix}`);
  if (def[`_route_${suffix}`]) lines.push(def[`_route_${suffix}`]);
  lines.push('');
  lines.push(`**Spanish triggers:**`);
  lines.push((triggers.es || []).map(t => `"${t}"`).join(', ') || '—');
  lines.push('');
  lines.push(`**English triggers:**`);
  lines.push((triggers.en || []).map(t => `"${t}"`).join(', ') || '—');
  lines.push('');
  return lines;
}

